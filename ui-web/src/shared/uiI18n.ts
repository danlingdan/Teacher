const sortedTranslations = [...translations].sort((left, right) => right[0].length - left[0].length);
const translatedAttributes = ["aria-label", "placeholder", "title"] as const;
const skippedTags = new Set(["CODE", "PRE", "SCRIPT", "STYLE", "TEXTAREA"]);

// 单遍正则替换：此前对每个文本节点做 ~360 次 split/join 全串扫描，
// 英文模式下每次 DOM 变更都会阻塞主线程。alternation 按长度降序排列，
// 保证更长词条优先匹配（与旧的逐条替换顺序一致）。
const translationBySource = new Map(sortedTranslations);
const translationPattern = new RegExp(
  sortedTranslations.map(([source]) => source.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")).join("|"),
  "g",
);

export function translateUiText(value: string) {
  if (!value) return value;
  return value.replace(translationPattern, match => translationBySource.get(match) ?? match);
}

function shouldSkip(node: Node) {
  const element = node.nodeType === Node.ELEMENT_NODE ? node as Element : node.parentElement;
  return Boolean(element?.closest(".monaco-editor, .knowledge-markdown, [data-no-translate]"))
    || Boolean(element && skippedTags.has(element.tagName));
}

function translateNode(node: Node) {
  if (shouldSkip(node)) return;
  if (node.nodeType === Node.TEXT_NODE && node.nodeValue) {
    const next = translateUiText(node.nodeValue);
    if (next !== node.nodeValue) node.nodeValue = next;
    return;
  }
  if (node.nodeType !== Node.ELEMENT_NODE) return;
  const element = node as Element;
  for (const attribute of translatedAttributes) {
    const value = element.getAttribute(attribute);
    if (value) element.setAttribute(attribute, translateUiText(value));
  }
  for (const child of Array.from(element.childNodes)) translateNode(child);
}

export function installEnglishUi(root: HTMLElement = document.body) {
  translateNode(root);
  const observer = new MutationObserver(records => {
    for (const record of records) {
      if (record.type === "characterData") translateNode(record.target);
      for (const node of Array.from(record.addedNodes)) translateNode(node);
    }
  });
  observer.observe(root, { childList: true, characterData: true, subtree: true });
  return () => observer.disconnect();
}
